"""Claude Code as a subprocess-backed provider.

The user already has a Claude Pro/Max subscription via the `claude`
CLI; we wrap it instead of asking for an API key. Each chat request
spawns the CLI with stream-json output and parses the line-delimited
events into our canonical ChunkEvents.

Trade-offs vs. the HTTP Anthropic provider:
  + No API key — uses the user's subscription auth (OAuth).
  + Multi-turn via --resume <session_id>.
  - Per-turn process spawn adds 0.5–2s startup latency.
  - The CLI streams *turns*, not tokens — text arrives in one chunk
    rather than smoothly. Still feels responsive for short replies.

══════════════════════════════════════════════════════════════════
SAFETY MODEL (re-designed; see claude_code_settings.py for the allowlist)
══════════════════════════════════════════════════════════════════
The spawned CLI inherits Claude Code's tool surface (Bash, Edit,
Write, Read, Grep, Glob, …). To keep that powerful but bounded, we
pin FOUR constraints, all hardwired here:

  1. **cwd = req.workspace, not $HOME.** Refuses to spawn if no
     workspace is provided, or if the workspace isn't inside the
     user's home directory (matches workspaces.is_within_home).
  2. **--settings <workspace-allowlist.json>**, generated by
     claude_code_settings.write(). The allowlist is workspace-scoped
     (Edit/Write/Read on `./**`, a curated set of read-only Bash
     patterns, plus a few auxiliaries). Mirrors CE's allowlist
     pattern — safe operations run silently, anything else hits a
     prompt.
  3. **`-p` (print mode)** is non-interactive: prompts can't be
     answered, so non-allowlisted tools auto-deny. Effectively
     "allowlist or refuse" without needing plan-mode.
  4. **--disallowed-tools** for truly off-limits surfaces
     (WebFetch, WebSearch, NotebookEdit, Task, EnterWorktree). These
     never even reach the prompt path.

We also strip ANTHROPIC_API_KEY from the env so the CLI cannot fall
through to API mode if both auths are configured; the rail agent must
use the subscription path the user explicitly opted into.

The earlier safety model used --permission-mode plan, which made
Bash/Edit/Write impossible. The user explicitly opted into a CE-style
allowlist redesign so the rail agent can actually do work in the
workspace; the path-scoped allowlist + cwd hardening + print-mode
auto-deny is the new safety floor.

Future MCP tool bridging adds switchbay daemon tools (recall_rail,
register_rule, view, …) via --mcp-config; those calls show up as
mcp__switchbay__<name> and need a corresponding allowlist entry.
"""

from __future__ import annotations

import asyncio
import json
import logging
import os
import shutil
from pathlib import Path
from typing import AsyncIterator

from .. import workspaces
from . import base, claude_code_settings

log = logging.getLogger("switchbay.llm.claude_code")

ID = "claude-code"
LABEL = "Claude Code"
DEFAULT_MODEL = "claude-sonnet-4-6"
PROBE_TIMEOUT_S = 30.0

# Hardwired-block tools — never reach the allowlist prompt. These are
# either escape vectors (sub-agents, worktrees, remote triggers) or
# capabilities switchbay explicitly doesn't want (network fetch,
# notebooks). Bash / Edit / Write / Read are scoped through the
# workspace allowlist instead of being blocked outright; see
# claude_code_settings.py.
DISALLOWED_TOOLS = ",".join([
    "Task",        # parallel sub-agent — could escape the sandbox
    "WebFetch",
    "WebSearch",
    "NotebookEdit",
    "EnterWorktree",
    "ExitWorktree",
    "RemoteTrigger",
    "PushNotification",
    "CronCreate",
    "CronDelete",
])

PROVIDER = {
    "id": ID,
    "label": LABEL,
    "category": "subscription",
    "default_model": DEFAULT_MODEL,
    # The `claude` CLI has no non-interactive "list models" command (its
    # /model picker is REPL-only), but `--model` accepts the aliases
    # opus/sonnet/haiku, which it resolves to the LATEST model of each
    # tier — so these auto-track new releases (e.g. opus → Opus 4.8 today,
    # the next Opus tomorrow) without a switchbay change. We list the
    # aliases first (recommended, always-latest) and pin specific
    # versions below for reproducibility.
    "model_suggestions": [
        "opus",
        "sonnet",
        "haiku",
        "claude-opus-4-8",
        "claude-opus-4-7",
        "claude-sonnet-4-6",
        "claude-haiku-4-5-20251001",
    ],
    "capabilities": {
        "chat": True,
        "streaming": True,
        "tools": False,
        # Execution surface — see base.CAPABILITY_NOTES.
        # spawns the Claude Code CLI; scoped by claude_code_settings + rail card.
        "shell": True,
        "file_write": True,
        "key_validation": True,
    },
    "binary": "claude",
    "auth_help": "Run `claude login` in a terminal to authenticate with your Pro/Max subscription.",
}


def is_installed() -> bool:
    return shutil.which(PROVIDER["binary"]) is not None


def _signed_in() -> bool:
    """Claude Code OAuth lives in ~/.claude.json (`oauthAccount`)."""
    p = Path.home() / ".claude.json"
    if not p.is_file():
        return bool(os.environ.get("ANTHROPIC_API_KEY"))
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return False
    if not isinstance(data, dict):
        return False
    oa = data.get("oauthAccount")
    if isinstance(oa, dict) and (oa.get("emailAddress") or oa.get("accountUuid")):
        return True
    return bool(os.environ.get("ANTHROPIC_API_KEY"))


def has_key() -> bool:
    """Available = CLI on PATH *and* signed in (not just installed)."""
    return is_installed() and _signed_in()


def _content_to_text(content: object) -> str:
    """Flatten a single message's content (string or block list) into text."""
    if isinstance(content, list):
        return " ".join(
            b.get("text", "") for b in content
            if isinstance(b, dict) and b.get("type") == "text"
        )
    return str(content)


def _flatten_messages(messages: list[dict]) -> str:
    parts: list[str] = []
    for m in messages:
        role = str(m.get("role", "user"))
        text = _content_to_text(m.get("content", ""))
        parts.append(f"{role.upper()}: {text}")
    return "\n\n".join(parts)


def _verify_workspace(raw: str | None) -> Path:
    """Hard gate: workspace must be supplied, exist, and live inside
    the user's home dir. Anything else aborts the spawn — there is no
    safe default cwd for a CLI with file/shell capability."""
    if not raw:
        raise base.ProviderError(
            "claude_code refuses to spawn without an explicit workspace cwd",
            code="server",
        )
    p = Path(raw)
    if not p.is_absolute() or not p.is_dir():
        raise base.ProviderError(
            f"claude_code workspace must be an absolute existing directory: {raw}",
            code="server",
        )
    if not workspaces.is_within_home(p):
        raise base.ProviderError(
            f"claude_code refuses to run with workspace outside {workspaces.home_label()}",
            code="server",
        )
    return p.resolve()


# ── Reasoning effort ────────────────────────────────────────────────
# `claude --effort <level>` — "Effort level for the current session".
# The enum is verified against the installed binary rather than assumed:
# passing an unknown value makes the CLI warn and fall back to its
# default, and it enumerates the valid set in that warning.
#
# Applies session-wide, which suits us: each turn is its own `claude -p`
# invocation, so the flag is effectively per-request.

_CLI_EFFORTS = ("low", "medium", "high", "xhigh", "max")


def reasoning_options(model: str | None = None) -> list[dict]:
    return [
        base.reasoning_option("low", "Low", "fastest and cheapest"),
        base.reasoning_option("medium", "Medium", "balanced"),
        base.reasoning_option("high", "High", "the usual choice for real work"),
        base.reasoning_option("xhigh", "Extra high", "harder problems, slower"),
        base.reasoning_option("max", "Max", "no ceiling — slowest and dearest"),
    ]


async def chat_stream(req: base.ChatRequest) -> AsyncIterator[base.ChunkEvent]:
    if not has_key():
        raise base.ProviderError(
            "`claude` not found on PATH. Install Claude Code from https://claude.com/claude-code.",
            code="missing-key",
        )

    workspace = _verify_workspace(req.workspace)

    if req.session_id:
        last = req.messages[-1] if req.messages else {"role": "user", "content": ""}
        prompt = _content_to_text(last.get("content", ""))
    else:
        prompt = _flatten_messages(req.messages)

    # Generate (or refresh) the workspace allowlist + MCP config files
    # before each spawn. Both writes are idempotent and cheap (no-ops
    # when content is unchanged); keeping them per-spawn means edits
    # to claude_code_settings.py / mcp_server take effect without
    # per-workspace migration. Off-thread: on a cloud-synced workspace
    # a file write can stall (or EDEADLK-retry) — never on the loop.
    settings_file = await asyncio.to_thread(
        claude_code_settings.write, workspace,
    )
    mcp_config_file = await asyncio.to_thread(
        claude_code_settings.write_mcp_config, workspace,
    )

    argv = [
        "claude",
        "-p", prompt,
        "--output-format", "stream-json",
        "--verbose",
        "--settings", str(settings_file),
        "--mcp-config", str(mcp_config_file),
        "--add-dir", str(workspace),
        "--disallowed-tools", DISALLOWED_TOOLS,
    ]
    if req.system:
        # Claude Code already has its own coding-assistant prompt;
        # we *append* ours so switchbay's rules (don't dump markdown,
        # link to pages instead) layer on top without replacing the
        # CLI's tool-use know-how.
        argv.extend(["--append-system-prompt", req.system])
    if req.session_id:
        argv.extend(["--resume", req.session_id])
    if req.model:
        argv.extend(["--model", req.model])
    effort = base.coerce_effort(req.reasoning_effort, reasoning_options(req.model))
    if effort:
        argv.extend(["--effort", effort])

    # Strip API key so the CLI can't fall through to API mode — must
    # use the subscription path. Also strip uv / venv leftovers that
    # could confuse subprocesses we ourselves don't run inside.
    env = {
        k: v for k, v in os.environ.items()
        if k not in {
            "ANTHROPIC_API_KEY",
            "ANTHROPIC_AUTH_TOKEN",
            "VIRTUAL_ENV",
            "UV_PROJECT_ENVIRONMENT",
            "PYTHONPATH",
        }
    }
    # Thread ownership for the permission hook: the hook forwards this
    # so the rail can scope the card to the owning thread. Spawns with
    # no owning thread (bench, headless curate, foreign callers) leave
    # it unset and their cards render in the "other approvals" strip.
    if req.origin_thread:
        env["CSWY_THREAD_ID"] = req.origin_thread
    from .. import cebridge
    env = cebridge.inject_skill_env(env)

    log.info("spawning claude in cwd=%s settings=%s", workspace, settings_file)
    try:
        proc = await asyncio.create_subprocess_exec(
            *argv,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            cwd=str(workspace),
            env=env,
            # asyncio's default StreamReader buffer is 64 KiB, which is
            # too small for some stream-json lines (Skill tool results,
            # Read on large files, large search outputs, …). 16 MiB is
            # generous headroom; if a line ever exceeds even this we'd
            # rather see the explicit failure than silently truncate.
            limit=16 * 1024 * 1024,
        )
    except FileNotFoundError as e:
        raise base.ProviderError(f"failed to spawn claude: {e}", code="missing-key", cause=e) from e

    stop_reason: str | None = None
    input_tokens: int | None = None
    output_tokens: int | None = None
    session_id: str | None = req.session_id

    if proc.stdout is None:
        raise base.ProviderError("claude subprocess produced no stdout", code="server")

    try:
        async for raw in proc.stdout:
            line = raw.decode("utf-8", errors="replace").strip()
            if not line:
                continue
            try:
                evt = json.loads(line)
            except json.JSONDecodeError:
                continue

            etype = evt.get("type")
            sid = evt.get("session_id")
            if isinstance(sid, str) and sid:
                session_id = sid

            if etype == "assistant":
                msg = evt.get("message") or {}
                for block in msg.get("content") or []:
                    btype = (block or {}).get("type")
                    if btype == "text":
                        text = block.get("text", "") or ""
                        if text:
                            yield base.TextChunk(text=text)
                    elif btype == "tool_use":
                        # The model wanted to invoke a CLI-side tool we
                        # haven't allowlisted. Surface as a notice, no
                        # execution — defense in depth alongside
                        # --disallowed-tools.
                        yield base.ToolUseChunk(
                            id=str(block.get("id", "")),
                            name=str(block.get("name", "")),
                            input=block.get("input") or {},
                        )
                usage = msg.get("usage") or {}
                if "input_tokens" in usage:
                    input_tokens = usage.get("input_tokens", input_tokens)
                if "output_tokens" in usage:
                    output_tokens = usage.get("output_tokens", output_tokens)
            elif etype == "result":
                stop_reason = evt.get("stop_reason") or stop_reason
                usage = evt.get("usage") or {}
                input_tokens = usage.get("input_tokens", input_tokens)
                output_tokens = usage.get("output_tokens", output_tokens)
                if evt.get("is_error"):
                    raise base.ProviderError(
                        f"Claude Code error: {evt.get('result') or 'unknown'}",
                        code="server",
                    )
    finally:
        try:
            await asyncio.wait_for(proc.wait(), timeout=2.0)
        except (asyncio.TimeoutError, ProcessLookupError):
            try:
                proc.kill()
            except ProcessLookupError:
                pass

    if proc.returncode and proc.returncode != 0:
        err = (await proc.stderr.read() if proc.stderr else b"").decode(errors="replace")
        raise base.ProviderError(
            f"claude exited {proc.returncode}: {err.strip()[:300] or 'no stderr'}",
            code="server",
        )

    yield base.DoneChunk(
        input_tokens=input_tokens,
        output_tokens=output_tokens,
        stop_reason=stop_reason,
        session_id=session_id,
    )


async def validate_key(*, workspace: str | None = None) -> bool:
    """Probe with a "ping" prompt — confirms the binary is logged in.
    Requires an absolute, in-home workspace path; matches the run-time
    cwd guarantees so a "Test" click can never escape the sandbox
    either."""
    if not has_key():
        raise base.ProviderError(
            "`claude` binary not found on PATH",
            code="missing-key",
        )
    req = base.ChatRequest(
        messages=[{"role": "user", "content": "respond with the word: ping"}],
        max_tokens=8,
        workspace=workspace,
    )
    try:
        async for _ in chat_stream(req):
            pass
    except base.ProviderError:
        raise
    except asyncio.TimeoutError as e:
        raise base.ProviderError("Claude Code probe timed out", code="timeout", cause=e) from e
    return True
